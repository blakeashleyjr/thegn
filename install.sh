#!/usr/bin/env bash
# install.sh — standalone (non-Nix) install of the native compositor host.
#
# Installs:
#   tg               — opens thegn in the CURRENT terminal (also forwards CLI verbs)
#   tg -s|--standalone — opens thegn in a dedicated alacritty window (bundled profile)
#   tg-tui           — always the current terminal (compat alias for `tg`)
#   thegn            — direct native host binary for CLI verbs/current-terminal use
# Plus a `.desktop` app-launcher entry (Exec=tg --standalone) with the owl icon.
set -euo pipefail

usage() {
  cat >&2 <<'EOF'
usage: ./install.sh [--dry-run] [bindir]

  --dry-run  print the install plan without building or changing files

bindir defaults to ~/.local/bin.
EOF
}

shell_quote() {
  printf '%q' "$1"
}

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
dry_run=0
bindir=""

while (($#)); do
  case "$1" in
  --dry-run)
    dry_run=1
    ;;
  -h | --help)
    usage
    exit 0
    ;;
  --*)
    echo "unknown option: $1" >&2
    usage
    exit 2
    ;;
  *)
    if [[ -n $bindir ]]; then
      echo "only one bindir may be provided" >&2
      usage
      exit 2
    fi
    bindir="$1"
    ;;
  esac
  shift
done

bindir="${bindir:-$HOME/.local/bin}"
: "${XDG_CONFIG_HOME:=$HOME/.config}"
: "${XDG_DATA_HOME:=$HOME/.local/share}"
[[ $XDG_CONFIG_HOME == /* ]] || XDG_CONFIG_HOME="$PWD/$XDG_CONFIG_HOME"
[[ $XDG_DATA_HOME == /* ]] || XDG_DATA_HOME="$PWD/$XDG_DATA_HOME"

if [[ $bindir != /* ]]; then
  echo "install.sh: bindir must be an absolute path: $bindir" >&2
  exit 2
fi

release_bin="$here/target/release/thegn"
alacritty_config="$here/config/alacritty.toml"
tg_tui="$bindir/tg-tui"
apps_dir="$XDG_DATA_HOME/applications"
desktop_file="$apps_dir/thegn.desktop"
icon_src="$here/config/thegn.svg"
icon_dir="$XDG_DATA_HOME/icons/hicolor/scalable/apps"
icon_file="$icon_dir/thegn.svg"
config_dir="$XDG_CONFIG_HOME/thegn"
config_file="$config_dir/config.toml"
manifest_dir="$XDG_DATA_HOME/thegn"
manifest_file="$manifest_dir/install-manifest"

# Launcher integration is per-platform, because the registry is:
#
#   Linux/BSD — a freedesktop `.desktop` entry + an hicolor icon (GNOME/KDE/rofi).
#   macOS     — a generated `thegn.app` bundle in ~/Applications, which is what
#               Spotlight/Raycast/Alfred/the Dock index (packaging/macos/make-app.sh).
#   Windows   — nothing yet; the binaries and wrappers still install normally.
#
# Opt OUT of the freedesktop path by name (rather than opting Linux in) so the
# BSDs, which do have freedesktop launchers, keep getting the entry.
desktop_integration=1
macos_app=0
macos_app_dir="$HOME/Applications"
make_app="$here/packaging/macos/make-app.sh"
case "$(uname -s)" in
Darwin)
  desktop_integration=0
  macos_app=1
  ;;
MINGW* | MSYS* | CYGWIN*) desktop_integration=0 ;;
esac

preflight_conflict=0
report_conflict() {
  echo "install.sh: refusing $1: $2" >&2
  preflight_conflict=1
}

check_file_shape() {
  local path="$1"
  if [[ -L $path ]]; then
    report_conflict "$path" "is a symlink"
  elif [[ -e $path && ! -f $path ]]; then
    report_conflict "$path" "is not a regular file"
  fi
}

owned_wrapper() {
  local path="$1" legacy="$2"
  [[ ! -e $path && ! -L $path ]] && return 0
  check_file_shape "$path"
  [[ -f $path && ($(<"$path") == *'# generated by thegn install.sh'* || $(<"$path") == *"$legacy"*) ]]
}

wrapper_execs_installed_binary() {
  local expected_exec
  expected_exec="exec $(shell_quote "$bindir/thegn") \"\$@\""
  [[ -f $tg_tui ]] && grep -Fqx -- "$expected_exec" "$tg_tui"
}

sha256() {
  local output
  if command -v sha256sum >/dev/null 2>&1; then
    output="$(sha256sum "$1")"
  elif command -v shasum >/dev/null 2>&1; then
    output="$(shasum -a 256 "$1")"
  else
    echo "install.sh: sha256sum or shasum is required to write the install manifest" >&2
    return 1
  fi
  printf '%s\n' "${output%% *}"
}

preflight() {
  preflight_conflict=0
  local dir
  for dir in "$bindir" "$config_dir"; do
    if [[ -L $dir ]]; then
      report_conflict "$dir" "is a symlink"
    elif [[ -e $dir && ! -d $dir ]]; then
      report_conflict "$dir" "is not a directory"
    fi
  done
  if ((desktop_integration)); then
    for dir in "$apps_dir" "$icon_dir" "$manifest_dir"; do
      if [[ -L $dir ]]; then
        report_conflict "$dir" "is a symlink"
      elif [[ -e $dir && ! -d $dir ]]; then
        report_conflict "$dir" "is not a directory"
      fi
    done
  else
    if [[ -L $manifest_dir ]]; then
      report_conflict "$manifest_dir" "is a symlink"
    elif [[ -e $manifest_dir && ! -d $manifest_dir ]]; then
      report_conflict "$manifest_dir" "is not a directory"
    fi
  fi
  if ((macos_app)); then
    if [[ -L $macos_app_dir ]]; then
      report_conflict "$macos_app_dir" "is a symlink"
    elif [[ -e $macos_app_dir && ! -d $macos_app_dir ]]; then
      report_conflict "$macos_app_dir" "is not a directory"
    fi
  fi
  if ((desktop_integration)) && [[ ! $bindir =~ ^[A-Za-z0-9/._+@-]+$ ]]; then
    report_conflict "$bindir" "contains characters unsafe in a freedesktop Exec field"
  fi
  check_file_shape "$bindir/thegn"
  if ! owned_wrapper "$tg_tui" 'export THEGN_ALACRITTY_CONFIG='; then
    report_conflict "$tg_tui" "existing wrapper is not recognized as installer-owned"
  elif [[ -f $bindir/thegn ]] && ! wrapper_execs_installed_binary; then
    report_conflict "$bindir/thegn" "existing binary is not referenced by an installer-owned tg-tui wrapper"
  fi
  if ! owned_wrapper "$bindir/tg" 'tg: alacritty not found'; then
    report_conflict "$bindir/tg" "existing wrapper is not recognized as installer-owned"
  fi

  if ((desktop_integration)); then
    check_file_shape "$desktop_file"
    if [[ -f $desktop_file ]] && ! grep -q '^X-Thegn-Installer=true$' "$desktop_file" &&
      ! { grep -q '^Name=thegn$' "$desktop_file" && grep -qE '^Exec=.*tg --standalone$' "$desktop_file"; }; then
      report_conflict "$desktop_file" "existing desktop entry is not recognized as installer-owned"
    fi
    check_file_shape "$icon_file"
    if [[ -f $icon_file && -f $icon_src ]] &&
      ! grep -q '<!-- generated by thegn install.sh -->' "$icon_file" && ! cmp -s "$icon_file" "$icon_src"; then
      report_conflict "$icon_file" "existing icon does not match the installer source"
    fi
  fi

  check_file_shape "$config_file"
}

preflight
if ((preflight_conflict)); then
  exit 1
fi

if ((dry_run)); then
  echo "dry-run: preflight passed; no files will be changed"
  echo "$bindir/thegn <- copy of $release_bin"
  echo "$bindir/tg-tui wrapper -> $bindir/thegn (current terminal)"
  echo "$bindir/tg wrapper -> $tg_tui (current terminal); tg -s|--standalone -> alacritty --config-file $alacritty_config -e $tg_tui"
  if ((desktop_integration)); then
    echo "$icon_file -> $icon_src (owl app icon)"
    echo "$desktop_file -> app-launcher entry (Exec=$bindir/tg --standalone, Icon=thegn)"
  elif ((macos_app)); then
    echo "$macos_app_dir/thegn.app -> Spotlight/Raycast/Dock launcher (opens a terminal running $bindir/thegn)"
  else
    echo "(no launcher entry — no .desktop registry and no macOS app bundle on this platform)"
  fi
  exit 0
fi

# mkdir is the portable atomic per-bindir lock primitive (including macOS).
mkdir -p "$bindir"
install_lock="$bindir/.thegn-install.lock"
if ! mkdir "$install_lock" 2>/dev/null; then
  lock_pid=""
  if [[ -f $install_lock/pid ]]; then
    IFS= read -r lock_pid <"$install_lock/pid" || true
  fi
  if [[ $lock_pid =~ ^[0-9]+$ ]] && kill -0 "$lock_pid" 2>/dev/null; then
    echo "install.sh: another install is running (pid $lock_pid); lock $install_lock" >&2
    exit 1
  fi
  if [[ ! -e $install_lock/pid ]]; then
    if stat -c %Y "$install_lock" >/dev/null 2>&1; then
      lock_mtime="$(stat -c %Y "$install_lock")"
    else
      lock_mtime="$(stat -f %m "$install_lock")"
    fi
    lock_age=$(($(date +%s) - lock_mtime))
    if ((lock_age <= 10)); then
      echo "install.sh: another install is starting; lock $install_lock" >&2
      exit 1
    fi
  fi
  rm -rf -- "$install_lock"
  if ! mkdir "$install_lock" 2>/dev/null; then
    echo "install.sh: could not reclaim install lock $install_lock" >&2
    exit 1
  fi
fi
remove_install_lock() {
  local lock_pid=""
  if [[ -f $install_lock/pid ]]; then
    IFS= read -r lock_pid <"$install_lock/pid" || true
  fi
  if [[ $lock_pid == "$$" ]]; then
    rm -rf -- "$install_lock"
  fi
}
trap remove_install_lock EXIT
printf '%s\n' "$$" >"$install_lock/pid.tmp"
mv -f -- "$install_lock/pid.tmp" "$install_lock/pid"

preflight
if ((preflight_conflict)); then
  exit 1
fi

declare -a journal_targets=() journal_backups=() staged_files=()
backup_dir=""
rollback_install() {
  local i target backup failed=0
  for ((i = ${#journal_targets[@]} - 1; i >= 0; i--)); do
    target="${journal_targets[i]}"
    backup="${journal_backups[i]}"
    if [[ $backup == new ]]; then
      if ! rm -f -- "$target"; then
        failed=1
      fi
    elif [[ -n $backup ]]; then
      if ! rm -f -- "$target" || ! mv -f -- "$backup" "$target"; then
        failed=1
      fi
    fi
  done
  return "$failed"
}
cleanup_install() {
  local status=$?
  trap - EXIT
  if ((status != 0)) && ((${#journal_targets[@]} > 0)); then
    if rollback_install; then
      echo "install.sh: install failed; restored the previous installation" >&2
    else
      echo "install.sh: install failed; rollback was incomplete" >&2
    fi
  fi
  if [[ -n $backup_dir ]]; then
    rm -rf -- "$backup_dir"
  fi
  if ((${#staged_files[@]} > 0)); then
    rm -f -- "${staged_files[@]}"
  fi
  remove_install_lock
  return "$status"
}
trap cleanup_install EXIT

assert_destination_dirs() {
  local dir
  for dir in "$bindir" "$config_dir" "$manifest_dir"; do
    if [[ -L $dir || (-e $dir && ! -d $dir) ]]; then
      echo "install.sh: refusing $dir: destination directory changed" >&2
      return 1
    fi
  done
  if ((desktop_integration)); then
    for dir in "$apps_dir" "$icon_dir"; do
      if [[ -L $dir || (-e $dir && ! -d $dir) ]]; then
        echo "install.sh: refusing $dir: destination directory changed" >&2
        return 1
      fi
    done
  fi
  if ((macos_app)) && [[ -L $macos_app_dir || (-e $macos_app_dir && ! -d $macos_app_dir) ]]; then
    echo "install.sh: refusing $macos_app_dir: destination directory changed" >&2
    return 1
  fi
}

commit_file() {
  local tmp="$1" target="$2" backup="new"
  assert_destination_dirs
  if [[ -e $target || -L $target ]]; then
    if [[ -z $backup_dir ]]; then
      backup_dir="$(mktemp -d "$bindir/.thegn-install-backup.XXXXXXXX")"
    fi
    backup="$backup_dir/${#journal_targets[@]}"
    mv -f -- "$target" "$backup"
  fi
  journal_targets+=("$target")
  journal_backups+=("$backup")
  mv -f -- "$tmp" "$target"
}

# THEGN_INSTALL_FAIL_AFTER is a test-only fault-injection seam.
maybe_inject_failure() {
  if [[ ${THEGN_INSTALL_FAIL_AFTER-} == "$1" ]]; then
    echo "install.sh: injected failure after $1" >&2
    exit 1
  fi
}

command -v cargo >/dev/null || {
  echo "cargo not found — install Rust or use 'nix profile install'." >&2
  exit 1
}

echo "building release binary…"
(cd "$here" && cargo build --release --workspace --features thegn-host/iroh)

if [[ ! -f $release_bin ]]; then
  echo "build reported success but $release_bin is missing — nothing to install." >&2
  exit 1
fi

# COPY, don't symlink into target/. A symlink to $here/target/release/thegn
# breaks the moment you `cargo clean`, prune the worktree, or move the repo —
# silently, and only when you next try to launch. An installed binary should
# survive the source tree it came from. Re-run install.sh to pick up a rebuild.
stage_file() {
  local target="$1" mode="$2"
  mkdir -p "$(dirname "$target")"
  staged_path="$(mktemp "$(dirname "$target")/.thegn-install.XXXXXXXX")"
  staged_files+=("$staged_path")
  chmod "$mode" "$staged_path"
}

stage_file "$bindir/thegn" 0755
binary_tmp="$staged_path"
install -m755 "$release_bin" "$binary_tmp"
commit_file "$binary_tmp" "$bindir/thegn"
maybe_inject_failure thegn
installed_bin="$bindir/thegn"

installed_bin_q="$(shell_quote "$installed_bin")"
alacritty_config_q="$(shell_quote "$alacritty_config")"
tg_tui_q="$(shell_quote "$tg_tui")"

# tg-tui: always the current terminal. THEGN_ALACRITTY_CONFIG points the in-app
# font picker at the alacritty profile it patches — the same bundled profile
# `tg --standalone` launches, so a font switch applies to both.
stage_file "$tg_tui" 0755
tg_tui_tmp="$staged_path"
cat >"$tg_tui_tmp" <<EOF
#!/usr/bin/env bash
# generated by thegn install.sh
set -euo pipefail
export THEGN_ALACRITTY_CONFIG=$alacritty_config_q
exec $installed_bin_q "\$@"
EOF
chmod 0755 "$tg_tui_tmp"
commit_file "$tg_tui_tmp" "$tg_tui"
maybe_inject_failure tg-tui

# tg: current terminal by default; `-s`/`--standalone` (must be the first arg)
# opens a dedicated alacritty window running the bundled, hermetic profile
# (`--config-file` replaces alacritty's default config search entirely, so your
# personal alacritty.toml stays out). Any other args (CLI verbs like `tg list`)
# run in the current terminal.
stage_file "$bindir/tg" 0755
tg_tmp="$staged_path"
cat >"$tg_tmp" <<EOF
#!/usr/bin/env bash
# generated by thegn install.sh
set -euo pipefail

if [[ \${1-} == -s || \${1-} == --standalone ]]; then
  shift
  if ! command -v alacritty >/dev/null 2>&1; then
    echo "tg: alacritty not found; install alacritty or run 'tg' to open thegn in the current terminal." >&2
    exit 127
  fi
  exec alacritty --config-file $alacritty_config_q -e $tg_tui_q "\$@"
fi

exec $tg_tui_q "\$@"
EOF
chmod 0755 "$tg_tmp"
commit_file "$tg_tmp" "$bindir/tg"
maybe_inject_failure tg

if ((desktop_integration)); then
  # Owl app icon: the same perched-sentinel mascot the loading splash draws
  # (config/thegn.svg, generated from crates/thegn-host/src/owl.rs). Installed
  # into the user's hicolor icon theme so `Icon=thegn` resolves in any launcher.
  mkdir -p "$icon_dir"
  if [[ -f $icon_src ]]; then
    stage_file "$icon_file" 0644
    icon_tmp="$staged_path"
    cp "$icon_src" "$icon_tmp"
    printf '\n<!-- generated by thegn install.sh -->\n' >>"$icon_tmp"
    commit_file "$icon_tmp" "$icon_file"
    maybe_inject_failure icon
    echo "wrote app icon: $icon_file"
  else
    echo "warning: $icon_src missing — desktop entry will fall back to a generic icon" >&2
  fi

  # App-launcher entry (GNOME/KDE/rofi/wofi/…): a `.desktop` file so thegn is
  # searchable/pinnable in your launcher. A GUI launcher has no terminal, so it
  # runs `tg --standalone` to open thegn's OWN alacritty window (`Terminal=false`).
  tg_launcher="$bindir/tg"
  mkdir -p "$apps_dir"
  stage_file "$desktop_file" 0644
  desktop_tmp="$staged_path"
  cat >"$desktop_tmp" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=thegn
X-Thegn-Installer=true
GenericName=Git Worktree IDE
Comment=Terminal-native git-worktree IDE + multiplexer
Exec=$tg_launcher --standalone
TryExec=$tg_launcher
Terminal=false
Icon=thegn
Categories=Development;IDE;RevisionControl;
Keywords=git;worktree;terminal;ide;multiplexer;thegn;
StartupNotify=true
EOF
  chmod 0644 "$desktop_tmp"
  commit_file "$desktop_tmp" "$desktop_file"
  maybe_inject_failure desktop
  # Refresh the launcher + icon caches so the entry/icon show up without a
  # re-login (best-effort — not all environments ship the tools).
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$apps_dir" 2>/dev/null || true
  command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -q -t -f "$XDG_DATA_HOME/icons/hicolor" 2>/dev/null || true
  echo "wrote app-launcher entry: $desktop_file"
fi

if ((macos_app)); then
  # macOS launcher: a generated `thegn.app` in ~/Applications. Generated here
  # rather than shipped so it carries no `com.apple.quarantine` xattr — a
  # downloaded .app would need Developer ID signing + notarization to open.
  # The app bundle is not included in the file rollback journal.
  if [[ -x $make_app ]]; then
    "$make_app" --bin "$bindir/thegn" --dest "$macos_app_dir" \
      --alacritty-config "$alacritty_config"
  else
    echo "warning: $make_app missing — no macOS app bundle written" >&2
  fi
fi

if [[ ! -e $config_file && ! -L $config_file ]]; then
  stage_file "$config_file" 0600
  config_tmp="$staged_path"
  cp "$here/config/config.toml.example" "$config_tmp"
  chmod 0600 "$config_tmp"
  if mv -n "$config_tmp" "$config_file"; then
    if [[ -e $config_tmp || -L $config_tmp ]]; then
      rm -f -- "$config_tmp"
    else
      journal_targets+=("$config_file")
      journal_backups+=(new)
      echo "wrote default config: $config_file"
    fi
  else
    exit 1
  fi
fi

mkdir -p "$manifest_dir"
stage_file "$manifest_file" 0644
manifest_tmp="$staged_path"
{
  printf 'thegn-install-manifest 1\n'
  for artifact in "$bindir/thegn" "$tg_tui" "$bindir/tg"; do
    artifact_absolute="$artifact"
    [[ $artifact_absolute == /* ]] || artifact_absolute="$PWD/$artifact_absolute"
    printf '%s\t%s\n' "$(sha256 "$artifact")" "$artifact_absolute"
  done
  if ((desktop_integration)); then
    if [[ -f $icon_file ]]; then
      artifact_absolute="$icon_file"
      [[ $artifact_absolute == /* ]] || artifact_absolute="$PWD/$artifact_absolute"
      printf '%s\t%s\n' "$(sha256 "$icon_file")" "$artifact_absolute"
    fi
    if [[ -f $desktop_file ]]; then
      artifact_absolute="$desktop_file"
      [[ $artifact_absolute == /* ]] || artifact_absolute="$PWD/$artifact_absolute"
      printf '%s\t%s\n' "$(sha256 "$desktop_file")" "$artifact_absolute"
    fi
  fi
} >"$manifest_tmp"
commit_file "$manifest_tmp" "$manifest_file"
maybe_inject_failure manifest
if [[ -n $backup_dir ]]; then
  rm -rf -- "$backup_dir"
  backup_dir=""
fi

# Warn about missing runtime deps (delta is used for diff output; alacritty backs
# the `tg --standalone` dedicated-window launcher).
command -v delta >/dev/null || echo "warning: 'delta' not found — diff output will lack syntax highlighting (install: https://github.com/dandavison/delta)" >&2
command -v alacritty >/dev/null || echo "warning: 'alacritty' not found — 'tg --standalone' opens a dedicated alacritty window; plain 'tg' opens thegn in the current terminal" >&2

echo "installed:"
echo "  $bindir/tg              -> current terminal ($bindir/thegn)"
echo "  $bindir/tg --standalone -> dedicated alacritty window using $alacritty_config"
echo "  $bindir/tg-tui          -> current-terminal native host ($bindir/thegn)"
echo "  $bindir/thegn           <- copy of $release_bin (re-run install.sh after a rebuild)"
# Only report the launcher files this platform actually got — the summary used
# to print the .desktop/icon paths on macOS too, where neither is written.
if ((desktop_integration)); then
  echo "  $icon_file              -> owl app icon"
  echo "  $desktop_file           -> app-launcher entry ('thegn')"
elif ((macos_app)); then
  echo "  $macos_app_dir/thegn.app  -> Spotlight/Raycast/Dock launcher ('thegn')"
fi
echo
echo "Ensure $bindir is on PATH, then run:  tg              # current terminal"
echo "                              or:  tg --standalone  # dedicated alacritty window"
echo "thegn shells out to:  git fzf (or gum) lazygit yazi delta gh"
echo
echo "Nix users: 'nix profile install $here#default' bundles the native host."
