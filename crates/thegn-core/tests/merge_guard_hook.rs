#[cfg(unix)]
#[test]
fn repaired_checkout_merges_again() {
    // The exact shape the old code left behind — our hook in the slot, the
    // framework's shim parked in `.thegn-orig` where the allow path execs it.
    // Before the fix that combination failed EVERY merge; after `install`
    // repairs it, a host merge works and the framework still runs.
    let dir = repo_with_shim("repaired");
    let hooks = dir.join(".git/hooks");
    write_exec(
        &hooks.join(merge_guard::CHAINED_NAME),
        FAKE_SHIM, // the displaced shim, poisoned into the chain
    );
    write_exec(
        &hooks.join(merge_guard::HOOK_NAME),
        merge_guard::HOOK_SCRIPT,
    );

    let plan = merge_guard::install(&hooks).unwrap();
    assert!(plan.restore_shim, "the shim must get its slot back");
    assert!(
        !hooks.join(merge_guard::CHAINED_NAME).exists(),
        "the parked shim must not be left in the chain"
    );

    let o = git(&dir, &["merge", "--no-ff", "side", "-m", "m"]);
    assert!(o.ok, "merge must work after repair: {}", o.stderr);
    assert!(o.stderr.contains("FRAMEWORK_RAN"), "stderr: {}", o.stderr);

    // …and the guard still bites when it should.
    let dir2 = repo_with_shim("repaired2");
    let hooks2 = dir2.join(".git/hooks");
    write_exec(&hooks2.join(merge_guard::CHAINED_NAME), FAKE_SHIM);
    write_exec(
        &hooks2.join(merge_guard::HOOK_NAME),
        merge_guard::HOOK_SCRIPT,
    );
    merge_guard::install(&hooks2).unwrap();
    let o2 = git_env(
        &dir2,
        &[("THEGN_SANDBOX", "1")],
        &["merge", "--no-ff", "side"],
    );
    assert!(
        !o2.ok,
        "guard must still refuse after repair: {}",
        o2.stderr
    );
    assert!(
        o2.stderr.contains("refusing to merge"),
        "stderr: {}",
        o2.stderr
    );

    let _ = std::fs::remove_dir_all(&dir);
    let _ = std::fs::remove_dir_all(&dir2);
}

/// The healthy framework arrangement, then a stray `prek install` reclaims the
/// slot and orphans the shim it displaced into `.thegn-orig`. Nothing repaired
/// this: `restore_shim` only fires when *our* hook is in the slot, and here a
/// shim is — so the orphan sat there breaking every merge.
#[cfg(unix)]
fn repo_with_orphaned_shim(tag: &str) -> std::path::PathBuf {
    let dir = repo_with_shim(tag);
    let hooks = dir.join(".git/hooks");
    merge_guard::install(&hooks).unwrap();
    write_exec(&hooks.join(merge_guard::CHAINED_NAME), MIGRATION_MODE_SHIM);
    dir
}

#[cfg(unix)]
#[test]
fn hook_script_skips_an_orphaned_shim() {
    // The installer only runs when thegn starts, so between the stray install
    // and the next launch the script itself has to cope. It must refuse to exec
    // a shim from the chained position rather than dying on its exit status.
    let dir = repo_with_orphaned_shim("orphan-runtime");

    let o = git(&dir, &["merge", "--no-ff", "side", "-m", "m"]);
    assert!(
        o.ok,
        "an orphaned shim must not break the merge: {}",
        o.stderr
    );
    assert!(
        !o.stderr.contains("migration mode"),
        "the orphan must not have been exec'd: {}",
        o.stderr
    );
    // The framework in the slot still ran — skipping the orphan is not silence.
    assert!(o.stderr.contains("FRAMEWORK_RAN"), "stderr: {}", o.stderr);
    let _ = std::fs::remove_dir_all(&dir);
}

#[cfg(unix)]
#[test]
fn install_clears_an_orphaned_shim() {
    let dir = repo_with_orphaned_shim("orphan-install");
    let hooks = dir.join(".git/hooks");

    let audit = merge_guard::audit(&hooks).unwrap();
    assert_eq!(
        audit.fault(),
        Some(merge_guard::Fault::ShimChained),
        "doctor must see it: {audit:?}"
    );

    let plan = merge_guard::install(&hooks).unwrap();
    assert!(plan.drop_chained, "the orphan must be removed: {plan:?}");
    assert!(!plan.restore_shim, "the slot already has its own shim");
    assert!(
        !hooks.join(merge_guard::CHAINED_NAME).exists(),
        "the orphaned shim must be gone"
    );
    assert_eq!(merge_guard::audit(&hooks).unwrap().fault(), None);

    // The guard survived the cleanup and still bites.
    let o = git_env(
        &dir,
        &[("THEGN_SANDBOX", "1")],
        &["merge", "--no-ff", "side"],
    );
    assert!(!o.ok, "guard must still refuse: {}", o.stderr);
    assert!(
        o.stderr.contains("refusing to merge"),
        "stderr: {}",
        o.stderr
    );
    let _ = std::fs::remove_dir_all(&dir);
}

#[cfg(unix)]
#[test]
fn a_user_hook_still_runs_when_we_own_the_slot() {
    // No framework: we take the slot and chain the user's hook, which must
    // still be able to refuse a merge on its own terms.
    let dir = scratch("userhook");
    must(&dir, &["init", "-q", "-b", "main"]);
    std::fs::write(dir.join("base.txt"), "base\n").unwrap();
    must(&dir, &["add", "-A"]);
    must(&dir, &["commit", "-q", "-m", "base"]);
    must(&dir, &["checkout", "-q", "-b", "side"]);
    std::fs::write(dir.join("side.txt"), "s\n").unwrap();
    must(&dir, &["add", "-A"]);
    must(&dir, &["commit", "-q", "-m", "side"]);
    must(&dir, &["checkout", "-q", "main"]);

    let hooks = dir.join(".git/hooks");
    write_exec(
        &hooks.join(merge_guard::HOOK_NAME),
        "#!/bin/sh\necho USER_HOOK_SAYS_NO >&2\nexit 3\n",
    );
    let plan = merge_guard::install(&hooks).unwrap();
    assert_eq!(plan.placement, Placement::Hook);
    assert_eq!(plan.action, InstallAction::Chained);

    // Not sandboxed → allow path → delegate to the chained user hook, which refuses.
    let o = git(&dir, &["merge", "--no-ff", "side", "-m", "m"]);
    assert!(!o.ok, "the chained user hook must still gate: {}", o.stderr);
    assert!(
        o.stderr.contains("USER_HOOK_SAYS_NO"),
        "stderr: {}",
        o.stderr
    );
    let _ = std::fs::remove_dir_all(&dir);
}
