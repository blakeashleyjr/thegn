#!/usr/bin/env python3
"""Generate a deterministic inventory of third-party Rust crates."""

import argparse
import difflib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"
HEADER_PARAGRAPHS = (
    "thegn is dual licensed under MIT OR Apache-2.0 (see `LICENSE-MIT` and `LICENSE-APACHE`).",
    "It is built from the Rust crates listed below. The licence of each crate is the SPDX expression its own manifest declares; the full licence text ships with that crate's source.",
    "This list covers every crate in `Cargo.lock`, including build-time and test-only dependencies, for all supported targets. It is generated by `scripts/third_party_notices.py` from `cargo metadata`; do not edit it by hand. Regenerate it with `just third-party-notices`.",
)


def version_key(version):
    """Return a comparison key that sorts numeric version components naturally."""
    return tuple(
        (0, int(part)) if part.isdigit() else (1, part)
        for part in re.split(r"[.+-]", version)
    )


def _package_sort_key(package):
    name = package["name"]
    return name.lower(), name, version_key(package["version"])


def _sorted_unique(packages):
    seen = set()
    result = []
    for package in sorted(packages, key=_package_sort_key):
        identity = (package["name"], package["version"])
        if identity not in seen:
            seen.add(identity)
            result.append(package)
    return result


def third_party_packages(metadata):
    """Select and normalize every non-workspace package in cargo metadata."""
    members = set(metadata["workspace_members"])
    packages = []
    for package in metadata["packages"]:
        if package["id"] in members:
            continue
        license_expression = package.get("license")
        license_file = package.get("license_file")
        if isinstance(license_expression, str) and license_expression:
            license_name = license_expression
        elif isinstance(license_file, str) and license_file:
            license_name = "see " + PurePosixPath(license_file).name
        else:
            license_name = "UNKNOWN"
        repository = package.get("repository")
        packages.append({
            "name": str(package["name"]),
            "version": str(package["version"]),
            "license": license_name,
            "repository": repository if isinstance(repository, str) else None,
        })
    return _sorted_unique(packages)


def _markdown_value(value):
    return str(value).replace("`", "'")


def render(packages):
    """Render crate records as stable, prettier-safe Markdown."""
    ordered = _sorted_unique(packages)
    lines = ["# Third-party notices", "", *HEADER_PARAGRAPHS, "", f"## Crates ({len(ordered)})", ""]
    for package in ordered:
        name = _markdown_value(package["name"])
        version = _markdown_value(package["version"])
        license_name = _markdown_value(package["license"])
        repository = package.get("repository")
        if not isinstance(repository, str) or any(char.isspace() for char in repository) or ">" in repository:
            repository_text = "no repository listed"
        else:
            repository_text = f"<{repository}>"
        lines.append(f"- `{name}` `{version}`: `{license_name}`, {repository_text}")
    return "\n".join(lines) + "\n"


def _fixture_metadata():
    workspace_id = "path+file:///w/crates/thegn-core#0.1.0"
    packages = [
        {"id": workspace_id, "name": "thegn-core", "version": "0.1.0", "license": "MIT", "repository": None},
        {"id": "registry+serde#1.0.200", "name": "serde", "version": "1.0.200", "license": "MIT OR Apache-2.0", "repository": "https://github.com/serde-rs/serde"},
        {"id": "registry+serde#1.0.9", "name": "serde", "version": "1.0.9", "license": "MIT OR Apache-2.0", "repository": "https://github.com/serde-rs/serde"},
        {"id": "registry+zlib-rs#0.4.0", "name": "zlib-rs", "version": "0.4.0", "license": None, "license_file": "LICENSE", "repository": None},
        {"id": "registry+mystery#2.0.0", "name": "mystery", "version": "2.0.0", "license": None, "license_file": None, "repository": "https://x.example/a b"},
        {"id": "path+file:///w/vendor/termwiz#0.22.0", "name": "termwiz", "version": "0.22.0", "source": None, "license": "MIT", "repository": "https://github.com/wezterm/wezterm"},
        {"id": "registry+zeta#1.0.0", "name": "Zeta", "version": "1.0.0", "license": "ISC", "repository": None},
    ]
    return {"workspace_members": [workspace_id], "packages": packages}


def _selftest():
    packages = third_party_packages(_fixture_metadata())
    names = [(item["name"], item["version"]) for item in packages]
    expected = [
        ("mystery", "2.0.0"), ("serde", "1.0.9"), ("serde", "1.0.200"),
        ("termwiz", "0.22.0"), ("Zeta", "1.0.0"), ("zlib-rs", "0.4.0"),
    ]
    if names != expected or any(name == "thegn-core" for name, _ in names):
        raise AssertionError("package selection or ordering self-test failed")
    by_name = {item["name"]: item for item in packages}
    if by_name["zlib-rs"]["license"] != "see LICENSE" or by_name["mystery"]["license"] != "UNKNOWN":
        raise AssertionError("licence fallback self-test failed")
    rendered = render(packages)
    if rendered != render(list(reversed(packages))) or "## Crates (6)" not in rendered:
        raise AssertionError("render self-test failed")


def _read_metadata(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        print(f"cannot read cargo metadata from {path}: {error}", file=sys.stderr)
        return None


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, help="read cargo metadata JSON from FILE")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="write notices to FILE")
    parser.add_argument("--check", action="store_true", help="check whether the output file is current")
    parser.add_argument("--selftest", action="store_true", help="run quick in-process fixture checks")
    args = parser.parse_args(argv)

    if args.selftest:
        _selftest()
        print("selftest ok")
        return 0

    if args.metadata is not None:
        metadata = _read_metadata(args.metadata)
        if metadata is None:
            return 2
    else:
        try:
            result = subprocess.run(
                ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"],
                cwd=ROOT,
                capture_output=True,
                text=True,
                check=False,
            )
        except FileNotFoundError:
            print("cargo is not installed; pass --metadata FILE", file=sys.stderr)
            return 2
        if result.returncode != 0:
            print("\n".join(result.stderr.splitlines()[:20]), file=sys.stderr)
            print("cargo metadata failed (offline?); pass --metadata FILE", file=sys.stderr)
            return 2
        try:
            metadata = json.loads(result.stdout)
        except json.JSONDecodeError as error:
            print(f"cargo metadata returned invalid JSON: {error}", file=sys.stderr)
            return 2

    generated = render(third_party_packages(metadata))
    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = ""
        except OSError as error:
            print(f"cannot read {args.output}: {error}", file=sys.stderr)
            return 2
        if current == generated:
            print("THIRD_PARTY_NOTICES.md is up to date")
            return 0
        print("THIRD_PARTY_NOTICES.md is stale: run `just third-party-notices`", file=sys.stderr)
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(args.output),
            tofile="generated",
            n=0,
        )
        for line in list(diff)[:10]:
            print(line, end="" if line.endswith("\n") else "\n", file=sys.stderr)
        return 1

    try:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
    except OSError as error:
        print(f"cannot write {args.output}: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
