#!/usr/bin/env bash
# Opt-in local Windows 11 VM for running the msvc tests on real Windows.
#
#   scripts/windows-vm.sh setup | up | down | status | ssh-config | test [crate [filter...]] | destroy
#   (just windows-vm-setup / windows-vm-up / windows-vm-down / test-windows-vm)
#
# Why: the windows-gnu cross-check proves Windows code compiles; only a real
# Windows kernel proves named pipes, Job Objects and ConPTY behave. The CI
# `windows` job does that at GitHub-runner prices and is opt-in for cost. This
# is the same check on a local KVM guest, for free, on demand.
#
# Linux + KVM only. quickemu/quickget (and through them qemu, OVMF, swtpm) come
# from the flake's pinned nixpkgs via `nix shell --inputs-from`, NOT from the
# dev shell: qemu is a ~1 GiB closure that nobody but this opt-in recipe uses,
# so adding it to devShells.default would tax every `nix develop` (and every CI
# job) for it. Nothing is fetched until `setup` runs.
#
# State lives OUTSIDE the repo, in $THEGN_WINVM_DIR (default
# $XDG_DATA_HOME/thegn-dev/windows-vm): the ISO (~6 GiB), virtio drivers, the
# qcow2 disk (grows to ~40-60 GiB with the toolchain and a target/), a VM-only
# ssh keypair and the ssh config the test recipes use. `destroy` deletes all of it.
#
# Media and licences — read before `setup`:
#   * `quickget windows 11` downloads Microsoft's consumer Windows 11 ISO from
#     Microsoft's own download API. It installs unactivated; that is fully
#     functional for testing, but using Windows still needs a licence of your
#     own. (quickget only fetches *evaluation* media for Windows Server, and
#     does not automate that install.)
#   * Provisioning installs Visual Studio Build Tools unattended, which
#     accepts its licence terms on your behalf.
#   Both are a human decision, so `setup` refuses to run without
#   THEGN_WINVM_ACCEPT_LICENSES=1.
#
# Tunables: THEGN_WINVM_CPUS (8), THEGN_WINVM_RAM (16G), THEGN_WINVM_DISK (96G,
# sparse), THEGN_WINVM_SSH_PORT (22220), THEGN_WINVM_MIN_FREE_GB (80),
# THEGN_WINVM_BOOT_TIMEOUT seconds for `up` to see a provisioned guest (5400:
# the first boot is a full unattended install plus the Build Tools download).
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
state=${THEGN_WINVM_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/thegn-dev/windows-vm}
vm=windows-11
conf="$state/$vm.conf"
vmdir="$state/$vm"
sshcfg="$state/ssh_config"
host_alias=thegn-winvm
port=${THEGN_WINVM_SSH_PORT:-22220}

die() {
  echo "windows-vm: $*" >&2
  exit 1
}

# quickemu/quickget and the ISO tooling, pinned by this repo's flake.lock.
qe() {
  nix shell --inputs-from "$repo" nixpkgs#quickemu nixpkgs#cdrtools --command "$@"
}

vssh() { ssh -F "$sshcfg" "$host_alias" "$@"; }

running() {
  [ -r "$vmdir/$vm.pid" ] && kill -0 "$(cat "$vmdir/$vm.pid")" 2>/dev/null
}

preflight() {
  [ "$(uname -s)" = Linux ] || die "Linux + KVM only (on a Mac, point test-remote at a Windows box instead)"
  [ -r /dev/kvm ] && [ -w /dev/kvm ] || die "/dev/kvm is not readable+writable by $(id -un); add yourself to the kvm group (NixOS: users.users.<you>.extraGroups = [ \"kvm\" ])"
  command -v nix >/dev/null 2>&1 || die "nix is required (quickemu comes from the flake's nixpkgs)"
}

write_ssh_config() {
  cat >"$sshcfg" <<EOF
# Generated by scripts/windows-vm.sh. Use with: ssh -F $sshcfg $host_alias
# (or add "Include $sshcfg" to ~/.ssh/config to reach it by name).
Host $host_alias
  HostName 127.0.0.1
  Port $port
  User Quickemu
  IdentityFile $state/id_ed25519
  IdentitiesOnly yes
  UserKnownHostsFile $state/known_hosts
  StrictHostKeyChecking accept-new
  ConnectTimeout 5
  ServerAliveInterval 30
EOF
}

cmd_setup() {
  preflight
  [ "${THEGN_WINVM_ACCEPT_LICENSES:-0}" = 1 ] ||
    die "setup downloads Windows 11 and installs Visual Studio Build Tools unattended. Read the 'Media and licences' note at the top of $0, then re-run with THEGN_WINVM_ACCEPT_LICENSES=1"
  mkdir -p "$state"
  local need=${THEGN_WINVM_MIN_FREE_GB:-80} free
  free=$(($(df -Pk "$state" | awk 'NR==2 {print $4}') / 1024 / 1024))
  [ "$free" -ge "$need" ] || die "only ${free} GiB free under $state; need ${need} GiB (THEGN_WINVM_MIN_FREE_GB)"

  [ -f "$state/id_ed25519" ] || ssh-keygen -q -t ed25519 -N '' -C thegn-winvm -f "$state/id_ed25519"

  if [ ! -f "$conf" ]; then
    echo "windows-vm: downloading Windows 11 + virtio drivers into $state (several GiB)..." >&2
    (cd "$state" && qe quickget windows 11)
  fi
  [ -f "$vmdir/unattended/autounattend.xml" ] || die "quickget produced no unattended install ($vmdir/unattended); see its output above"

  # Our provisioning rides on quickget's unattended ISO (mounted as F: during
  # first logon, which is where quickget's own commands find their MSIs): add
  # the script + public key, and one FirstLogonCommand after quickget's six.
  cp "$repo/test/windows-vm/provision.ps1" "$vmdir/unattended/thegn-provision.ps1"
  cp "$state/id_ed25519.pub" "$vmdir/unattended/thegn-winvm.pub"
  if ! grep -q thegn-provision "$vmdir/unattended/autounattend.xml"; then
    local cmd='<SynchronousCommand wcm:action="add"><CommandLine>powershell -NoProfile -ExecutionPolicy Bypass -File F:\\thegn-provision.ps1</CommandLine><Description>thegn test-remote provisioning</Description><Order>50</Order></SynchronousCommand>'
    sed -i "s|</FirstLogonCommands>|$cmd</FirstLogonCommands>|" "$vmdir/unattended/autounattend.xml"
  fi
  rm -f "$vmdir/unattended.iso"
  qe mkisofs -quiet -J -o "$vmdir/unattended.iso" "$vmdir/unattended/"

  # quickemu sources the .conf as bash, so later assignments win.
  sed -i '/^# thegn-winvm$/,$d' "$conf"
  cat >>"$conf" <<EOF
# thegn-winvm
cpu_cores="${THEGN_WINVM_CPUS:-8}"
ram="${THEGN_WINVM_RAM:-16G}"
disk_size="${THEGN_WINVM_DISK:-96G}"
ssh_port="$port"
EOF
  write_ssh_config
  echo "windows-vm: set up in $state. Next: just windows-vm-up (first boot installs Windows unattended; allow ~30-60 min)." >&2
}

cmd_up() {
  preflight
  [ -f "$conf" ] || die "not set up; run: THEGN_WINVM_ACCEPT_LICENSES=1 just windows-vm-setup"
  write_ssh_config
  if ! running; then
    # quickemu backgrounds qemu itself; setsid keeps it alive past this shell.
    # shellcheck disable=SC2016 # $0/$@ belong to the inner bash
    (cd "$state" && setsid -f bash -c 'exec "$@" >"$0" 2>&1' "$state/quickemu.log" \
      nix shell --inputs-from "$repo" nixpkgs#quickemu --command quickemu --vm "$conf" --display none)
  fi
  local deadline=$((SECONDS + ${THEGN_WINVM_BOOT_TIMEOUT:-5400}))
  echo "windows-vm: waiting for a provisioned guest on 127.0.0.1:$port (log: $state/quickemu.log)..." >&2
  until vssh 'if exist C:\thegn-provision.done (exit 0) else (exit 1)' </dev/null >/dev/null 2>&1; do
    [ $SECONDS -lt $deadline ] || die "guest not provisioned after ${THEGN_WINVM_BOOT_TIMEOUT:-5400}s. Look at the console (quickemu --vm $conf with a display) and C:\\thegn-provision.log in the guest"
    sleep 20
  done
  echo "windows-vm: up — ssh -F $sshcfg $host_alias" >&2
}

cmd_down() {
  if ! running; then
    echo "windows-vm: not running" >&2
    return 0
  fi
  # A clean shutdown first: killing qemu mid-write can corrupt the NTFS image.
  vssh 'shutdown /s /t 0' </dev/null >/dev/null 2>&1 || true
  for _ in $(seq 1 60); do
    running || break
    sleep 2
  done
  if running; then
    echo "windows-vm: guest ignored shutdown; killing qemu" >&2
    (cd "$state" && qe quickemu --vm "$conf" --kill)
  fi
  echo "windows-vm: down" >&2
}

cmd_status() {
  echo "state:   $state ($(du -sh "$state" 2>/dev/null | cut -f1 || echo absent))"
  echo "kvm:     $([ -r /dev/kvm ] && [ -w /dev/kvm ] && echo usable || echo 'NOT usable')"
  if running; then echo "vm:      running (pid $(cat "$vmdir/$vm.pid"))"; else echo "vm:      stopped"; fi
  if [ -f "$sshcfg" ] && vssh 'if exist C:\thegn-provision.done (exit 0) else (exit 1)' </dev/null >/dev/null 2>&1; then
    echo "ssh:     reachable + provisioned (ssh -F $sshcfg $host_alias)"
  else
    echo "ssh:     unreachable or not yet provisioned"
  fi
}

# The default Windows gate mirrors the CI `windows` job (.github/workflows/
# ci.yml): a workspace check plus the test groups validated on msvc so far.
# The full `cargo test --workspace` is not green on Windows yet, so running it
# by default would only report known failures. Keep this list in step with ci.yml.
ci_windows_cmd() {
  cat <<'EOF'
$steps = @(
  'cargo check --workspace --locked',
  'cargo test -p thegn-svc --lib --locked ipc',
  'cargo test -p thegn-svc --lib --locked plugin::platform::native_tests::',
  'cargo test -p thegn-svc --lib --locked plugin::platform::windows::tests::',
  'cargo test -p thegn-host --locked platform::'
)
foreach ($s in $steps) {
  [Console]::Error.WriteLine("==> $s")
  Invoke-Expression $s
  if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}
EOF
}

cmd_test() {
  cmd_up
  local -a env=(THEGN_REMOTE_OS=windows THEGN_REMOTE_SSH_CONFIG="$sshcfg")
  if [ $# -eq 0 ] && [ -z "${THEGN_REMOTE_CMD:-}" ]; then
    env+=(THEGN_REMOTE_CMD="$(ci_windows_cmd)")
  fi
  env "${env[@]}" "$repo/scripts/test-remote.sh" "$host_alias" "$@"
}

cmd_destroy() {
  if [ -d "$state" ]; then
    local state_real home_real
    state_real=$(realpath -m -- "$state")
    home_real=$(realpath -m -- "$HOME")
    [ "$state_real" != / ] || die "refusing to destroy filesystem root"
    [ "$state_real" != "$home_real" ] || die "refusing to destroy your home directory"
    [ -f "$conf" ] || die "refusing to destroy $state: no VM state marker ($conf)"
  fi
  cmd_down
  [ -d "$state" ] || return 0
  echo "windows-vm: deleting $state ($(du -sh "$state" | cut -f1))" >&2
  rm -rf "$state"
}

sub=${1:-}
[ $# -gt 0 ] && shift
case "$sub" in
setup) cmd_setup ;;
up) cmd_up ;;
down) cmd_down ;;
status) cmd_status ;;
ssh-config)
  write_ssh_config
  cat "$sshcfg"
  ;;
test) cmd_test "$@" ;;
destroy) cmd_destroy ;;
*)
  sed -n '2,5p' "$0" | sed 's/^# \{0,1\}//' >&2
  exit 2
  ;;
esac
